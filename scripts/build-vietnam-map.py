ts.append(f"    {{ name: 'Quần đảo Hoàng Sa', province: 'Đà Nẵng', ...{pt(111.9, 16.45)} }},\n")
ts.append(f"    {{ name: 'Quần đảo Trường Sa', province: 'Khánh Hòa', ...{pt(112.3, 10.2)} }},\n]\n")
