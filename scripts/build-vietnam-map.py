def inside(lon, lat, rings):
    c = False
    for r in rings:
        for i in range(len(r)):
            (x1, y1), (x2, y2) = r[i], r[i - 1]
            if (y1 > lat) != (y2 > lat) and lon < (x2 - x1) * (lat - y1) / (y2 - y1) + x1: c = not c
    return c
for n, (lon, lat) in CITIES.items():
    hit = [x['name'] for x in provs if inside(lon, lat, x['rings'])]
    if not hit:  # offshore point after simplification: nearest centre
        X, Y = P(lon, lat); hit = [min(provs, key=lambda q: (q['center'][0]-X)**2 + (q['center'][1]-Y)**2)['name']]
    x_, y_ = P(lon, lat)
    ts.append(f'    {json.dumps(n, ensure_ascii=False)}: {{ x: {x_:.1f}, y: {y_:.1f}, province: {json.dumps(hit[0], ensure_ascii=False)} }},\n')
    print(n, '->', hit)
