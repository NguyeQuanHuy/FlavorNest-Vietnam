import json, math, sys
src, out_ts = sys.argv[1], sys.argv[2]
d = json.load(open(src))
LON0, LAT_TOP, K = 102.0, 23.5, 66.0
COS = math.cos(math.radians(16))
def P(lon, lat): return ((lon - LON0) * COS * K, (LAT_TOP - lat) * K)

REGION = {
 'north': ['Hà Nội','Hải Phòng','Quảng Ninh','Bắc Ninh','Hưng Yên','Ninh Bình','Phú Thọ','Thái Nguyên','Tuyên Quang','Lào Cai','Lai Châu','Điện Biên','Sơn La','Cao Bằng','Lạng Sơn'],
 'central': ['Thanh Hóa','Nghệ An','Hà Tĩnh','Quảng Trị','Huế','Đà Nẵng','Quảng Ngãi','Gia Lai','Đắk Lắk','Khánh Hòa'],
 'south': ['TP. Hồ Chí Minh','Đồng Nai','Tây Ninh','Cần Thơ','Vĩnh Long','Đồng Tháp','An Giang','Cà Mau','Lâm Đồng'],
}
reg_of = {n: r for r, ns in REGION.items() for n in ns}
EN = {'TP. Hồ Chí Minh': 'Ho Chi Minh City', 'Hà Nội': 'Hanoi', 'Huế': 'Huế'}

def ring_area(r):  # planar, projected
    a = 0
    for i in range(len(r)):
        x1, y1 = r[i]; x2, y2 = r[(i + 1) % len(r)]
        a += x1 * y2 - x2 * y1
    return a / 2
def geo_area_km2(polys):
    # equal-area approx: shoelace on (lon*cos(lat) , lat) in km
    tot = 0
    for poly in polys:
        for j, ring in enumerate(poly):
            pts = [((lon) * 111.32 * math.cos(math.radians(lat)), lat * 110.57) for lon, lat in ring]
            a = abs(ring_area(pts))
            tot += a if j == 0 else -a
    return tot

provs = []
for f in d['features']:
    p = dict(f['properties']); g = f['geometry']
    if p['Ma'] == '31':  # source data mislabels Đồng Tháp as Lạng Sơn
        p.update(TinhThanh='Đồng Tháp', SapNhap='Đồng Tháp, Tiền Giang', SoXa=None, DanSo_ng=None, Dtich_km2=None)
    polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
    parts = []; best = (0, None)
    for poly in polys:
        for j, ring in enumerate(poly):
            pts = [P(*c) for c in ring]
            if len(pts) < 4: continue
            seg = 'M' + 'L'.join(f'{x:.1f},{y:.1f}' for x, y in pts[:-1]) + 'Z'
            # drop consecutive duplicate points after rounding
            parts.append(seg)
            if j == 0:
                a = abs(ring_area(pts))
                if a > best[0]:
                    cx = sum(x for x, _ in pts) / len(pts); cy = sum(y for _, y in pts) / len(pts)
                    best = (a, (round(cx, 1), round(cy, 1)))
    name = p['TinhThanh']
    merged = [s.strip().replace('TP HCM', 'TP. Hồ Chí Minh').replace('Đăk Lăk', 'Đắk Lắk').replace('Hoà Bình', 'Hòa Bình') for s in p['SapNhap'].split(',')]
    rings_ll = [ring for poly in polys for ring in poly]
    provs.append(dict(
        rings=rings_ll, code=p['Ma'], name=name, nameEn=EN.get(name, name), city=p['Loai'] == 'Thành phố',
        region=reg_of[name], merged=merged if len(merged) > 1 else [],
        communes=int(p['SoXa']) if p.get('SoXa') else None,
        areaKm2=round(p['Dtich_km2']) if p.get('Dtich_km2') else round(geo_area_km2(polys) / 10) * 10,
        population=int(p['DanSo_ng']) if p.get('DanSo_ng') else None,
        center=best[1], d=''.join(parts)))
assert len(provs) == 34 and len({x['name'] for x in provs}) == 34, 'names'
provs.sort(key=lambda x: x['code'])

W = round((112.9 - LON0) * COS * K); H = round((LAT_TOP - 8.3) * K)
def pt(lon, lat): x, y = P(lon, lat); return f'{{ x: {x:.1f}, y: {y:.1f} }}'
